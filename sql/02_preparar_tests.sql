-- Ejecutar conectado a la base de datos empresa_test como administrador (postgres).

CREATE TABLE cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE
);


GRANT CONNECT ON DATABASE empresa_test TO gestion_app;
GRANT USAGE ON SCHEMA public TO gestion_app;
GRANT SELECT, INSERT ON TABLE public.cliente TO gestion_app;
GRANT USAGE ON SEQUENCE public.cliente_id_seq TO gestion_app;
GRANT UPDATE ON TABLE public.cliente TO gestion_app;
